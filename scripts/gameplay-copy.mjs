const workshopUnlockMachines = new Set(["m03", "m04", "m08"]);

export function describeItem(id, name, kind, machineByItem) {
  if (itemCopy[id]) return itemCopy[id];
  const machine = machineByItem.get(id);
  if (machine) {
    const summary = buildingCopy[machine.id] ?? machine.description;
    return `可在厂区地图上安装 1 台「${machine.name}（${machine.code}）」，拆除时完整退回总仓库。${summary ? `设备用途：${summary}` : ""}`;
  }
  throw new Error(`Missing natural item copy for ${id} (${name}, ${kind})`);
}

export function describeRecipe(recipe, machineById, machineByItem) {
  if (recipeCopy[recipe.id]) return recipeCopy[recipe.id];
  const outIds = Object.keys(recipe.outputs);
  if (outIds.length === 1) {
    const targetMachine = machineByItem.get(outIds[0]);
    if (targetMachine) {
      const summary = buildingCopy[targetMachine.id] ?? "";
      const firstSentence = summary.split("。")[0];
      const workshopTip = workshopUnlockMachines.has(targetMachine.id)
        ? `；首次制造后解锁工作室中的「${earlyMachineNames[targetMachine.id].workshop}」功能，无需安装设备`
        : "";
      return `制造 1 台可放置在厂区地图上的「${targetMachine.name}（${targetMachine.code}）」${workshopTip}。${firstSentence ? `${firstSentence}。` : ""}`;
    }
  }
  const machine = machineById.get(recipe.building_type);
  return recipe.description || `${machine?.name ?? "产线"}标准加工工序。`;
}
